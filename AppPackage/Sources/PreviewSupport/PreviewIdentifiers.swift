    /// The parsed table.
    ///
    /// `compactMap` silently drops a literal it cannot parse, which would shift every later
    /// index and quietly change the identity a call site has been resolving all along. The count
    /// is therefore asserted rather than trusted, so a typo in the table above surfaces in debug
    /// as a failure here instead of as an inexplicable preview diff much later.
    private static let all: [UUID] = {
        let parsed = uuidStrings.compactMap(UUID.init(uuidString:))
        if parsed.count != uuidStrings.count {
            assertionFailure(
                "PreviewIdentifiers: \(uuidStrings.count - parsed.count) malformed UUID literal(s) in the table"
            )
        }
        return parsed
    }()

    /// The sole access point into the table.
    ///
    /// Traps on an out-of-range index rather than substituting a fresh or wrapped-around value:
    /// a preview that has outgrown the table is a mistake worth failing loudly, and a silent
    /// substitute would reintroduce exactly the non-determinism this type exists to remove.
    public static subscript(index: Int) -> UUID {
        precondition(all.indices.contains(index), "PreviewIdentifiers index \(index) is out of bounds")
        // reason: bounds are precondition-checked immediately above.
        return all[index]
    }
