@testable import VisualSnapshotSupport
import XCTest

/// Coordinate inputs use the same headline ramp and cover roles as the production views. Home's center and
/// neighbors use hero, Frontpage uses standard, and Toplists uses compact. Downloads uses standard throughout.
/// Reader controls are hidden in these fixtures, so its preview images are not displayed.
@MainActor
struct FixtureArtwork {
    let pixelSizes: [String: CGSize]
    let contentSizeCategory: UIContentSizeCategory
    let displayScale: CGFloat

    init(traits: UITraitCollection, displayScale: CGFloat, readerPagePixelWidth: Int) {
        self.contentSizeCategory = traits.preferredContentSizeCategory
        self.displayScale = displayScale
        var sizes: [String: CGSize] = [:]
        for (index, gallery) in PublicVisualFixtures.homeGalleries.enumerated() {
            let style: GalleryCoverStyle = index == 0 ? .hero : (index < 3 ? .standard : .compact)
            sizes[gallery.coverPath] = Self.coverPixelSize(style, traits: traits, displayScale: displayScale)
        }
        for gallery in PublicVisualFixtures.homeCarouselNeighbors {
            sizes[gallery.coverPath] = Self.coverPixelSize(.hero, traits: traits, displayScale: displayScale)
        }
        for gallery in PublicVisualFixtures.downloadGalleries {
            sizes[gallery.coverPath] = Self.coverPixelSize(.standard, traits: traits, displayScale: displayScale)
        }
        for page in 1...PublicVisualFixtures.readerPageMarkers.count {
            sizes["assets/reader/\(page).png"] = CGSize(
                width: readerPagePixelWidth, height: Int((Double(readerPagePixelWidth) * 11 / 8).rounded())
            )
        }
        pixelSizes = sizes
    }

    static func coverPointSize(
        _ style: GalleryCoverStyle, traits: UITraitCollection, displayScale: CGFloat
    ) -> CGSize {
        style.size(
            scale: UIFontMetrics(forTextStyle: .headline).scaledValue(for: 1, compatibleWith: traits),
            displayScale: displayScale
        )
    }

    private static func coverPixelSize(
        _ style: GalleryCoverStyle, traits: UITraitCollection, displayScale: CGFloat
    ) -> CGSize {
        let size = coverPointSize(style, traits: traits, displayScale: displayScale)
        return CGSize(width: size.width * displayScale, height: size.height * displayScale)
    }

    /// Keep the coordinate's generated bytes, their dimensions and the canonical input identity together.
    @discardableResult
    func export(to directory: URL, sourceDigest: String? = nil, scenarios: Data? = nil) throws -> PublicFixtureExport {
        let result = try PublicVisualFixtures.export(
            to: directory, scenarios: scenarios, artworkPixelSizes: pixelSizes
        )
        var record: [String: Any] = [
            "fixtureVersion": PublicVisualFixtures.fixtureVersion, "aggregateDigest": result.aggregateDigest,
            "contentSizeCategory": contentSizeCategory.rawValue, "displayScale": displayScale,
            "artworkPixelSizes": pixelSizes.mapValues({ ["width": $0.width, "height": $0.height] })
        ]
        if let sourceDigest { record["sourceAggregateDigest"] = sourceDigest }
        try JSONSerialization.data(withJSONObject: record, options: [.prettyPrinted, .sortedKeys])
            .write(to: directory.deletingLastPathComponent().appending(path: "artwork-sizing.json"), options: .atomic)
        return result
    }

    /// Check dimensions and every source pixel outside a cover's four curve-containing corner squares. Equal extents
    /// miss the half-pixel content shift possible at an origin tie. Reader pages have no corner exclusion.
    /// Cropping before canonical conversion avoids allocating another full-content RGBA buffer for this check.
    func assertNotResampled(
        _ evidence: FullContentCaptureEvidence, fixtures: URL, output: URL,
        file: StaticString = #filePath, line: UInt = #line
    ) throws {
        let covers = PublicVisualFixtures.homeGalleries + PublicVisualFixtures.downloadGalleries
        var paths = Dictionary(uniqueKeysWithValues: covers.map({ ($0.title, $0.coverPath) }))
        for (index, marker) in PublicVisualFixtures.readerPageMarkers.enumerated() {
            paths[marker] = "assets/reader/\(index + 1).png"
        }
        let capture = try XCTUnwrap(UIImage(contentsOfFile: evidence.fullImageURL.path)?.cgImage)
        var records: [[String: Any]] = []
        var failedAssets: [String] = []
        for (title, frame) in evidence.itemFrames.sorted(by: { $0.key < $1.key }) {
            try autoreleasepool {
                let path = try XCTUnwrap(paths[title], "Unregistered artwork: \(title)", file: file, line: line)
                let expected = try XCTUnwrap(pixelSizes[path], file: file, line: line)
                let image = try XCTUnwrap(UIImage(contentsOfFile: fixtures.appending(path: path).path)?.cgImage)
                let exported = CGSize(width: image.width, height: image.height)
                let measured = CGSize(
                    width: (frame.width * evidence.viewport.scale).rounded(),
                    height: (frame.height * evidence.viewport.scale).rounded()
                )
                let pixelFrame = CGRect(
                    x: (frame.minX * evidence.viewport.scale).rounded(),
                    y: (frame.minY * evidence.viewport.scale).rounded(), width: measured.width, height: measured.height
                )
                var record: [String: Any] = [
                    "title": title, "asset": path, "exportedPixels": [exported.width, exported.height],
                    "measuredPixels": [measured.width, measured.height], "frame": NSCoder.string(for: frame),
                    "pixelFrame": NSCoder.string(for: pixelFrame), "dimensionsMatched": measured == exported
                ]
                if exported == expected, measured == exported {
                    let cropped = try XCTUnwrap(capture.cropping(to: pixelFrame), file: file, line: line)
                    let cornerPixels = path.hasPrefix("assets/reader/") ? 0 : try Self.coverCornerExtentPixels(
                        size: frame.size, displayScale: evidence.viewport.scale
                    )
                    let comparison = try Self.comparePixels(
                        source: image, captured: cropped, cornerExtentPixels: cornerPixels
                    )
                    record.merge(comparison.diagnostics, uniquingKeysWith: { _, new in new })
                    record["cornerExtentPixels"] = cornerPixels
                    if comparison.differingPixels > 0 { failedAssets.append(path) }
                } else {
                    record["contentComparison"] = "not-run-dimension-mismatch"
                    failedAssets.append(path)
                }
                records.append(record)
            }
        }
        try JSONSerialization.data(withJSONObject: records, options: [.prettyPrinted, .sortedKeys])
            .write(to: output.appending(path: "artwork-verification.json"), options: .atomic)
        guard !records.isEmpty else { throw FixtureArtworkError.noArtwork }
        guard failedAssets.isEmpty else { throw FixtureArtworkError.artworkPixelsChanged(failedAssets) }
    }

    /// The continuous curve spans about 1.527 radii on this runtime. Its renderer coverage differs from vector
    /// containment inside that region; beyond it, pixel-aligned straight edges leave every source pixel covered.
    /// Derive the extent from the shared shape, rather than using that observed ratio as a mask constant.
    static func coverCornerExtentPixels(size: CGSize, displayScale: CGFloat) throws -> Int {
        guard size.width.isFinite, size.height.isFinite, size.width > 0, size.height > 0,
              displayScale.isFinite, displayScale > 0 else { throw FixtureArtworkError.invalidComparisonDimensions }
        let path = GalleryCover.clipShape.path(in: CGRect(origin: .zero, size: size)).cgPath
        var extent: CGFloat = 0
        for horizontal in [true, false] {
            var lower: CGFloat = 0
            var upper = (horizontal ? size.width : size.height) / 2
            // Sample just inside the edge to avoid boundary-membership ambiguity. Sixty bisections resolve
            // its curve transition below device-pixel precision; this is geometry, not a pixel-diff tolerance.
            let edgeInset: CGFloat = 1e-9
            let midpoint = horizontal ? CGPoint(x: upper, y: edgeInset) : CGPoint(x: edgeInset, y: upper)
            guard path.contains(midpoint) else {
                throw FixtureArtworkError.invalidComparisonDimensions
            }
            for _ in 0..<60 {
                let middle = (lower + upper) / 2
                let point = horizontal ? CGPoint(x: middle, y: edgeInset) : CGPoint(x: edgeInset, y: middle)
                if path.contains(point) {
                    upper = middle
                } else {
                    lower = middle
                }
            }
            extent = max(extent, upper)
        }
        return Int(ceil(extent * displayScale))
    }

    static func comparePixels(
        source: CGImage, captured: CGImage, cornerExtentPixels: Int
    ) throws -> FixtureArtworkPixelComparison {
        guard source.width == captured.width, source.height == captured.height,
              cornerExtentPixels >= 0, cornerExtentPixels * 2 < min(source.width, source.height) else {
            throw FixtureArtworkError.invalidComparisonDimensions
        }
        let expected = try CapturedRaster(image: source)
        let actual = try CapturedRaster(image: captured)
        var result = FixtureArtworkPixelComparison()
        expected.pixels.withUnsafeBytes { expectedBytes in
            actual.pixels.withUnsafeBytes { actualBytes in
                for row in 0..<source.height {
                    for column in 0..<source.width {
                        let edgeRow = row < cornerExtentPixels || row >= source.height - cornerExtentPixels
                        let edgeColumn = column < cornerExtentPixels || column >= source.width - cornerExtentPixels
                        if edgeRow && edgeColumn { continue }
                        result.comparedPixels += 1
                        let start = (row * source.width + column) * 4
                        // Equal dimensions and the raster's byte-count invariant bound every four-byte read.
                        let expectedPixel = expectedBytes.loadUnaligned(fromByteOffset: start, as: UInt32.self)
                        let actualPixel = actualBytes.loadUnaligned(fromByteOffset: start, as: UInt32.self)
                        guard expectedPixel != actualPixel else { continue }
                        result.differingPixels += 1
                        for component in 0..<4 {
                            let channel = start + component
                            let difference = abs(Int(expectedBytes[channel]) - Int(actualBytes[channel]))
                            result.maximumChannelDifference = max(result.maximumChannelDifference, difference)
                        }
                        if result.firstDifference == nil {
                            result.firstDifference = CGPoint(x: column, y: row)
                            result.firstSourceRGBA = Array(expectedBytes[start..<(start + 4)])
                            result.firstCapturedRGBA = Array(actualBytes[start..<(start + 4)])
                        }
                    }
                }
            }
        }
        return result
    }
}

struct FixtureArtworkPixelComparison {
    var comparedPixels = 0
    var differingPixels = 0
    var maximumChannelDifference = 0
    var firstDifference: CGPoint?
    var firstSourceRGBA: [UInt8] = []
    var firstCapturedRGBA: [UInt8] = []

    var diagnostics: [String: Any] {
        var values: [String: Any] = [
            "comparedPixels": comparedPixels, "differingPixels": differingPixels,
            "maximumChannelDifference": maximumChannelDifference, "contentMatched": differingPixels == 0
        ]
        if let firstDifference {
            values["firstDifferenceInArtworkPixels"] = [firstDifference.x, firstDifference.y]
            values["firstSourceRGBA"] = firstSourceRGBA
            values["firstCapturedRGBA"] = firstCapturedRGBA
        }
        return values
    }
}

private enum FixtureArtworkError: Error {
    case invalidComparisonDimensions
    case noArtwork
    case artworkPixelsChanged([String])
}
