#!/usr/bin/env bash
#
# Signing for the AltStore PAL notarization build (`.github/workflows/deploy-pal.yml`, Phase 20 plan 20-04).
#
# Usage:
#   marketplace-signing.sh api-key
#       writes the App Store Connect API key (APP_STORE_CONNECT_PRIVATE_KEY) to a file and exports ASC_KEY_PATH
#   marketplace-signing.sh setup
#       makes a temporary keychain with the distribution certificate, installs both provisioning profiles,
#       and writes the signing xcconfig and the export options; exports MARKETPLACE_XCCONFIG,
#       MARKETPLACE_EXPORT_OPTIONS and MARKETPLACE_KEYCHAIN
#   marketplace-signing.sh teardown
#       deletes the keychain, the installed profiles and every file the other commands wrote; never fails
#   marketplace-signing.sh xcconfig-only <out> <team> <app profile> <share extension profile>
#       writes only the signing xcconfig, touching no keychain or profile directory (offline check)
#   marketplace-signing.sh export-options-only <out> <team> <app profile> <share extension profile>
#       writes only the export options (offline check)
#
# Environment (from the `pal-notarization` GitHub environment's secrets; never printed):
#   RUNNER_TEMP                                   where everything is written
#   APP_STORE_CONNECT_KEY_ID, APP_STORE_CONNECT_PRIVATE_KEY
#                                                 api-key: the key's ID and the .p8 file's contents
#   APPLE_TEAM_ID                                 setup: the team that owns the certificate and profiles
#   DISTRIBUTION_CERTIFICATE,
#   DISTRIBUTION_CERTIFICATE_PASSWORD             setup: the Apple Distribution certificate (base64 .p12)
#   PROVISIONING_PROFILE_APP,
#   PROVISIONING_PROFILE_SHARE_EXTENSION          setup: the two App Store Connect profiles (base64)
#
# Why a generated xcconfig: `-xcconfig` takes one file and applies it to every target, and the app and the
# share extension need different profiles. So the file includes Config/Marketplace.xcconfig and selects each
# target's profile by name with `PROVISIONING_PROFILE_SPECIFIER = $(EHPANDA_PROFILE_$(TARGET_NAME))`; package
# targets expand to empty (Research §5). Signing is manual. Nothing here asks Xcode to create or download a
# profile, certificate or App ID (D-07).

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MARKETPLACE_XCCONFIG_PATH="$ROOT/Config/Marketplace.xcconfig"
EXPORT_OPTIONS_TEMPLATE="$ROOT/actions-tool/ExportOptions-marketplace.plist"
# The marketplace flavor's identifiers (`app.ehpanda` + Marketplace.xcconfig's BUNDLE_ID_SUFFIX).
APP_BUNDLE_ID="app.ehpanda.store"
SHARE_BUNDLE_ID="app.ehpanda.store.ShareExtension"
# Xcode 16 and later read profiles from the first directory; earlier tools from the second.
PROFILE_DIRS=(
  "$HOME/Library/Developer/Xcode/UserData/Provisioning Profiles"
  "$HOME/Library/MobileDevice/Provisioning Profiles"
)

fail() {
  echo "::error::$*" >&2
  exit 1
}

work_dir() {
  [[ -n "${RUNNER_TEMP:-}" ]] || fail "RUNNER_TEMP is not set."
  printf '%s/marketplace-signing' "$RUNNER_TEMP"
}

require() {
  local name
  for name in "$@"; do
    [[ -n "${!name:-}" ]] || fail "$name is not set."
  done
}

export_env() {
  # Hands a path to the later steps of the job.
  if [[ -n "${GITHUB_ENV:-}" ]]; then
    printf '%s=%s\n' "$1" "$2" >> "$GITHUB_ENV"
  fi
}

check_team() {
  [[ "$1" =~ ^[A-Z0-9]{10}$ ]] || fail "The team ID is not ten letters and digits."
}

check_profile_name() {
  # A profile name ends up as an xcconfig value: one line, and nothing xcconfig would read as a comment or a
  # build-setting reference.
  local name="$1"
  [[ -n "$name" ]] || fail "A provisioning profile name is empty."
  [[ "$name" != *$'\n'* && "$name" != *'//'* && "$name" != *'$('* && "$name" != *'${'* ]] ||
    fail "The provisioning profile name '$name' cannot be written to an xcconfig file."
}

write_xcconfig() {
  local out="$1" team="$2" app_profile="$3" share_profile="$4"
  check_team "$team"
  check_profile_name "$app_profile"
  check_profile_name "$share_profile"
  [[ -f "$MARKETPLACE_XCCONFIG_PATH" ]] || fail "$MARKETPLACE_XCCONFIG_PATH is missing."
  mkdir -p "$(dirname "$out")"
  {
    echo "// Generated by actions-tool/marketplace-signing.sh for one deploy-pal.yml run, and deleted after it."
    echo "#include \"$MARKETPLACE_XCCONFIG_PATH\""
    echo ""
    echo "DEVELOPMENT_TEAM = $team"
    echo "CODE_SIGN_STYLE = Manual"
    echo "CODE_SIGN_IDENTITY = Apple Distribution"
    echo "CODE_SIGN_IDENTITY[sdk=iphoneos*] = Apple Distribution"
    echo "EHPANDA_PROFILE_EhPanda = $app_profile"
    echo "EHPANDA_PROFILE_ShareExtension = $share_profile"
    echo "PROVISIONING_PROFILE_SPECIFIER = \$(EHPANDA_PROFILE_\$(TARGET_NAME))"
  } > "$out"
}

write_export_options() {
  local out="$1" team="$2" app_profile="$3" share_profile="$4" profiles
  check_team "$team"
  check_profile_name "$app_profile"
  check_profile_name "$share_profile"
  mkdir -p "$(dirname "$out")"
  cp "$EXPORT_OPTIONS_TEMPLATE" "$out"
  profiles="$(jq -cn --arg app "$APP_BUNDLE_ID" --arg appProfile "$app_profile" \
    --arg share "$SHARE_BUNDLE_ID" --arg shareProfile "$share_profile" \
    '{($app): $appProfile, ($share): $shareProfile}')"
  plutil -replace teamID -string "$team" "$out"
  plutil -replace provisioningProfiles -json "$profiles" "$out"
  plutil -lint -s "$out"
}

profile_field() {
  # profile_field <decoded profile plist> <key path>
  plutil -extract "$2" raw -o - "$1" 2>/dev/null || true
}

install_profile() {
  # install_profile <base64 variable> <bundle ID> <team>: prints the profile's name
  local variable="$1" bundle_id="$2" team="$3" dir profile decoded uuid name app_id profile_team
  dir="$(work_dir)"
  profile="$dir/$variable.mobileprovision"
  decoded="$dir/$variable.plist"
  printf '%s' "${!variable}" | base64 --decode > "$profile" 2>/dev/null || fail "$variable is not base64."
  security cms -D -i "$profile" > "$decoded" 2>/dev/null || fail "$variable is not a provisioning profile."
  uuid="$(profile_field "$decoded" UUID)"
  name="$(profile_field "$decoded" Name)"
  app_id="$(profile_field "$decoded" Entitlements.application-identifier)"
  profile_team="$(profile_field "$decoded" TeamIdentifier.0)"
  [[ "$uuid" =~ ^[0-9A-Fa-f-]{36}$ ]] || fail "$variable has no UUID."
  [[ "$profile_team" == "$team" ]] || fail "$variable belongs to team $profile_team, not APPLE_TEAM_ID."
  [[ "$app_id" == "$team.$bundle_id" ]] || fail "$variable is for $app_id, not $team.$bundle_id."
  check_profile_name "$name"
  for target_dir in "${PROFILE_DIRS[@]}"; do
    mkdir -p "$target_dir"
    cp "$profile" "$target_dir/$uuid.mobileprovision"
    printf '%s\n' "$target_dir/$uuid.mobileprovision" >> "$dir/installed-profiles"
  done
  printf '%s' "$name"
}

api_key() {
  require APP_STORE_CONNECT_KEY_ID APP_STORE_CONNECT_PRIVATE_KEY
  [[ "$APP_STORE_CONNECT_KEY_ID" =~ ^[A-Z0-9]+$ ]] || fail "APP_STORE_CONNECT_KEY_ID is not letters and digits."
  local dir key
  dir="$(work_dir)/private_keys"
  mkdir -p "$dir"
  chmod 700 "$(work_dir)" "$dir"
  key="$dir/AuthKey_$APP_STORE_CONNECT_KEY_ID.p8"
  ( umask 077; printf '%s\n' "$APP_STORE_CONNECT_PRIVATE_KEY" > "$key" )
  grep -q -- "-----BEGIN PRIVATE KEY-----" "$key" || fail "APP_STORE_CONNECT_PRIVATE_KEY is not a .p8 key."
  export_env ASC_KEY_PATH "$key"
  echo "Wrote the App Store Connect API key."
}

setup() {
  require APPLE_TEAM_ID DISTRIBUTION_CERTIFICATE DISTRIBUTION_CERTIFICATE_PASSWORD PROVISIONING_PROFILE_APP PROVISIONING_PROFILE_SHARE_EXTENSION
  check_team "$APPLE_TEAM_ID"
  local dir keychain password app_profile share_profile xcconfig export_options line
  dir="$(work_dir)"
  mkdir -p "$dir"
  chmod 700 "$dir"
  keychain="$RUNNER_TEMP/marketplace-signing.keychain-db"
  xcconfig="$RUNNER_TEMP/marketplace-signing.xcconfig"
  export_options="$RUNNER_TEMP/ExportOptions-marketplace.plist"

  # The keychain search list as it was, restored at teardown.
  security list-keychains -d user | sed -e 's/^[[:space:]]*"//' -e 's/"[[:space:]]*$//' > "$dir/keychains"
  printf '%s\n' "$keychain" > "$dir/keychain"

  password="$(openssl rand -hex 24)"
  ( umask 077; printf '%s' "$DISTRIBUTION_CERTIFICATE" | base64 --decode > "$dir/certificate.p12" ) 2>/dev/null ||
    fail "DISTRIBUTION_CERTIFICATE is not base64."
  security create-keychain -p "$password" "$keychain"
  security set-keychain-settings -lut 21600 "$keychain"
  security unlock-keychain -p "$password" "$keychain"
  security import "$dir/certificate.p12" -k "$keychain" -f pkcs12 -P "$DISTRIBUTION_CERTIFICATE_PASSWORD" \
    -T /usr/bin/codesign -T /usr/bin/security >/dev/null || fail "The certificate could not be imported."
  rm -f "$dir/certificate.p12"
  security set-key-partition-list -S apple-tool:,apple: -s -k "$password" "$keychain" >/dev/null
  local search=("$keychain")
  while IFS= read -r line; do
    if [[ -n "$line" && "$line" != "$keychain" ]]; then
      search+=("$line")
    fi
  done < "$dir/keychains"
  security list-keychains -d user -s "${search[@]}"
  security find-identity -v -p codesigning "$keychain" | grep -q '"Apple Distribution: ' ||
    fail "The certificate is not an Apple Distribution identity."

  app_profile="$(install_profile PROVISIONING_PROFILE_APP "$APP_BUNDLE_ID" "$APPLE_TEAM_ID")"
  share_profile="$(install_profile PROVISIONING_PROFILE_SHARE_EXTENSION "$SHARE_BUNDLE_ID" "$APPLE_TEAM_ID")"
  write_xcconfig "$xcconfig" "$APPLE_TEAM_ID" "$app_profile" "$share_profile"
  write_export_options "$export_options" "$APPLE_TEAM_ID" "$app_profile" "$share_profile"

  export_env MARKETPLACE_XCCONFIG "$xcconfig"
  export_env MARKETPLACE_EXPORT_OPTIONS "$export_options"
  export_env MARKETPLACE_KEYCHAIN "$keychain"
  echo "Signing is set up: the app uses '$app_profile', the share extension '$share_profile'."
}

teardown() {
  set +e
  local dir line keychain="" restore=()
  dir="$(work_dir 2>/dev/null)" || exit 0
  if [[ -f "$dir/keychain" ]]; then
    keychain="$(cat "$dir/keychain")"
  fi
  if [[ -f "$dir/keychains" ]]; then
    while IFS= read -r line; do
      [[ -n "$line" && "$line" != "$keychain" ]] && restore+=("$line")
    done < "$dir/keychains"
    if (( ${#restore[@]} > 0 )); then
      security list-keychains -d user -s "${restore[@]}"
    fi
  fi
  if [[ -n "$keychain" ]]; then
    security delete-keychain "$keychain" 2>/dev/null
    rm -f "$keychain"
  fi
  if [[ -f "$dir/installed-profiles" ]]; then
    while IFS= read -r line; do
      [[ -n "$line" ]] && rm -f "$line"
    done < "$dir/installed-profiles"
  fi
  rm -rf "$dir" "$RUNNER_TEMP/marketplace-signing.xcconfig" "$RUNNER_TEMP/ExportOptions-marketplace.plist"
  echo "Signing material removed."
  exit 0
}

command="${1:-}"
shift || true
case "$command" in
  api-key) api_key ;;
  setup) setup ;;
  teardown) teardown ;;
  xcconfig-only)
    (( $# == 4 )) || fail "Usage: marketplace-signing.sh xcconfig-only <out> <team> <app profile> <share profile>"
    write_xcconfig "$@" ;;
  export-options-only)
    (( $# == 4 )) || fail "Usage: marketplace-signing.sh export-options-only <out> <team> <app profile> <share profile>"
    write_export_options "$@" ;;
  *) fail "Usage: marketplace-signing.sh api-key|setup|teardown|xcconfig-only|export-options-only" ;;
esac
